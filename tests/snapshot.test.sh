FAILURES=0
CHECKS=0
pass() { CHECKS=$((CHECKS + 1)); printf '  ok   - %s\n' "$1"; }
fail() { CHECKS=$((CHECKS + 1)); FAILURES=$((FAILURES + 1)); printf '  FAIL - %s\n' "$1"; }
note() { printf '  --   - %s (skipped)\n' "$1"; }

# Run a python3 helper script (heredoc'd to $WORK below); dynamic values are passed as argv, not
# string-interpolated into the script, so the checks below are safe to write as plain Python.
check_py() {
  local desc="$1" script="$2"; shift 2
  local out
  if out=$("$PY" "$script" "$@" 2>&1); then
    pass "$desc"
  else
    fail "$desc"
    printf '%s\n' "$out" | sed 's/^/         /'
  fi
}

# Run a shell command, expecting exit code 0.
check_ok() {
  local desc="$1"; shift
  local out
  if out=$("$@" 2>&1); then
    pass "$desc"
  else
    fail "$desc"
    printf '%s\n' "$out" | sed 's/^/         /'
  fi
}

# Run a shell command, expecting a non-zero exit code, and (optionally, if $2 is non-empty)
# grep its combined output for a required substring. Always call with an explicit $2 (pass ""
# to skip the substring check) -- every argument after that is the command to run.
check_fails() {
  local desc="$1" needle="$2"; shift 2
  local out rc
  out=$("$@" 2>&1); rc=$?
  if [ "$rc" -eq 0 ]; then
    fail "$desc (expected non-zero exit, got 0)"
    return
  fi
  if [ -n "$needle" ] && ! printf '%s' "$out" | grep -qF -e "$needle"; then
    fail "$desc (exit $rc, but message did not mention '$needle')"
    printf '%s\n' "$out" | sed 's/^/         /'
    return
  fi
  pass "$desc"
}

