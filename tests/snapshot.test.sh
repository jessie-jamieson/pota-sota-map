# Touches no network. Prints "ok"/"FAIL" per check and exits non-zero if anything failed.
#
#   bash tests/snapshot.test.sh
#
# Requires: python3 (3.9+), node (only for the two "output is valid JS" checks -- if node is not
# on PATH those two checks are skipped with a note, everything else still runs).
